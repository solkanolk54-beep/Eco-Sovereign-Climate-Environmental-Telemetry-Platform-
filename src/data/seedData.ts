export const POSTGIS_SCHEMA_SQL = `-- Eco-Sovereign Climate & Environmental Telemetry Platform
-- PostgreSQL 16 + PostGIS 3.4 Spatial Database Schema

CREATE EXTENSION IF NOT EXISTS postgis;

-- 1. Administrative & Ecological Regions (Wilayas)
CREATE TABLE regions (
    id SERIAL PRIMARY KEY,
    name_ar VARCHAR(100) NOT NULL,
    name_en VARCHAR(100) NOT NULL,
    wilaya_code VARCHAR(10) UNIQUE NOT NULL,
    ecosystem_zone VARCHAR(40) NOT NULL,
    geom GEOMETRY(MultiPolygon, 4326),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_regions_geom ON regions USING GIST(geom);

-- 2. IoT Telemetry Stations
CREATE TABLE telemetry_stations (
    id SERIAL PRIMARY KEY,
    station_code VARCHAR(50) UNIQUE NOT NULL,
    station_type VARCHAR(50) NOT NULL,
    region_id INT REFERENCES regions(id),
    location GEOMETRY(Point, 4326) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    last_ping TIMESTAMP
);
CREATE INDEX idx_stations_location ON telemetry_stations USING GIST(location);

-- 3. High-Frequency Climate & Spectral Readings
CREATE TABLE climate_readings (
    id SERIAL PRIMARY KEY,
    station_id INT REFERENCES telemetry_stations(id),
    temperature DECIMAL(5,2),
    humidity DECIMAL(5,2),
    wind_speed DECIMAL(5,2),
    soil_moisture DECIMAL(5,2),
    ndvi_index DECIMAL(4,3),
    ndwi_index DECIMAL(4,3),
    lst_celsius DECIMAL(5,2),
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_climate_readings_time ON climate_readings(recorded_at DESC);

-- 4. Spatial Anomalies & Wildfire Risks
CREATE TABLE spatial_anomalies (
    id SERIAL PRIMARY KEY,
    anomaly_type VARCHAR(50) NOT NULL,
    severity_level INT CHECK (severity_level BETWEEN 1 AND 5),
    description TEXT,
    geom GEOMETRY(Point, 4326) NOT NULL,
    status VARCHAR(20) DEFAULT 'active',
    detected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_spatial_anomalies_geom ON spatial_anomalies USING GIST(geom);

-- 5. Water Reservoirs & Dams
CREATE TABLE water_reservoirs (
    id SERIAL PRIMARY KEY,
    reservoir_code VARCHAR(40) UNIQUE NOT NULL,
    name_ar VARCHAR(120) NOT NULL,
    name_en VARCHAR(120) NOT NULL,
    region_id INT REFERENCES regions(id),
    capacity_mcm DECIMAL(10,2) NOT NULL,
    current_fill_pct DECIMAL(5,2) NOT NULL,
    groundwater_depletion_m_yr DECIMAL(5,2),
    geom GEOMETRY(Point, 4326) NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reservoirs_geom ON water_reservoirs USING GIST(geom);

-- 6. Encrypted Anonymous Field Reports
CREATE TABLE field_reports (
    id SERIAL PRIMARY KEY,
    encrypted_hash VARCHAR(64) NOT NULL,
    category VARCHAR(50) NOT NULL,
    details TEXT NOT NULL,
    geom GEOMETRY(Point, 4326) NOT NULL,
    is_anonymous BOOLEAN DEFAULT TRUE,
    verification_status VARCHAR(30) DEFAULT 'pending_inspection',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_field_reports_geom ON field_reports USING GIST(geom);`;
